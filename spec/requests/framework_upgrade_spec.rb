require 'rails_helper'

RSpec.describe "Framework upgrade compatibility", type: :request do
  it "keeps Ransack filters and sorting when following Pagy links" do
    league = create(:league)
    teams = %w[Alpha Bravo Charlie].map do |name|
      create(:team, league: league, territory: "Metro #{name}")
    end
    create(:team, league: league, territory: "Elsewhere")

    get teams_path, params: { q: { territory_cont: "Metro", s: "territory desc" }, per_page: 2 }
    expect(response).to have_http_status(:success)
    document = Nokogiri::HTML(response.body)
    expect(document.css("#teams .index-record").map { |record| record['id'] })
      .to eq(["team_#{teams[2].id}", "team_#{teams[1].id}"])
    expect(document.at_css('.pagy [aria-current="page"]').text).to eq("1")

    get document.at_css('.pagy a[rel="next"]')['href']
    expect(response).to have_http_status(:success)
    document = Nokogiri::HTML(response.body)
    expect(document.css("#teams .index-record").map { |record| record['id'] })
      .to eq(["team_#{teams[0].id}"])
    expect(document.at_css('.pagy [aria-current="page"]').text).to eq("2")
  end

  it "keeps the team scope and page size when paginating players" do
    team = create(:team)
    players = %w[Alpha Bravo Charlie].map { |name| create(:player, team: team, first_name: name) }
    outsider = create(:player, first_name: "Outsider")

    get team_players_path(team), params: { per_page: 2 }
    expect(response).to have_http_status(:success)
    document = Nokogiri::HTML(response.body)
    expect(document.css('.player-record').size).to eq(2)
    next_url = URI.parse(document.at_css('.pagy a[rel="next"]')['href'])
    expect(next_url.path).to eq(team_players_path(team))
    expect(Rack::Utils.parse_nested_query(next_url.query)).to include('per_page' => '2', 'page' => '2')

    get next_url.to_s
    expect(response).to have_http_status(:success)
    document = Nokogiri::HTML(response.body)
    expect(document.css('.player-record').size).to eq(1)
    expect(response.body).to include(players.last.first_name)
    expect(response.body).not_to include(players.first.first_name, outsider.first_name)
  end

  it "resets a password using the link generated by Devise 5" do
    ace = create(:ace)
    post ace_password_path, params: { ace: { email: ace.email } }
    expect(response).to have_http_status(:see_other)
    link = Nokogiri::HTML(ActionMailer::Base.deliveries.last.body.decoded).at_css('a')['href']
    token = Rack::Utils.parse_nested_query(URI.parse(link).query).fetch('reset_password_token')

    get URI.parse(link).request_uri
    expect(response).to have_http_status(:success)
    put ace_password_path, params: {
      ace: { reset_password_token: token, password: 'replacement123', password_confirmation: 'replacement123' }
    }
    expect(response).to have_http_status(:see_other)
    expect(ace.reload.valid_password?('replacement123')).to be(true)
    expect(ace.valid_password?('password123')).to be(false)
    expect(ace.reset_password_token).to be_nil
  end

  it "confirms an account using the link generated by Devise 5" do
    ace = create(:ace, :unconfirmed)
    ace.send_confirmation_instructions
    link = Nokogiri::HTML(ActionMailer::Base.deliveries.last.body.decoded).at_css('a')['href']

    get URI.parse(link).request_uri
    expect(response).to redirect_to(new_ace_session_path)
    expect(ace.reload).to be_confirmed
  end
end
